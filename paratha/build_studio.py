"""Generates the AI Studio (TanStack Start) version of the Paratha Land pages.
   python3 paratha/build_studio.py
   Writes src/paratha/content.gen.ts, home.css, catering.css and the init modules."""
import json, re, pathlib, sys
HERE = pathlib.Path(__file__).parent
sys.path.insert(0, str(HERE))
import build as B

OUT = HERE.parent / "src" / "paratha"
OUT.mkdir(parents=True, exist_ok=True)

def page(name):
    p = B.build("ghl") / f"{name}.html"
    s = p.read_text()
    style = re.search(r"<style>(.*?)</style>", s, re.S).group(1)
    body = re.search(r"<body[^>]*>(.*)</body>", s, re.S).group(1)
    body = re.sub(r"<script\b[^>]*>.*?</script>", "", body, flags=re.S).strip()
    return style, body

home_css, home_body = page("index")
cat_css, cat_body = page("catering")
guide_css, guide_body = page(B.GUIDE_SLUG)
(OUT / "home.css").write_text(home_css)
(OUT / "catering.css").write_text(cat_css + "\nhtml,body{background:#fbf1dc}\n")
(OUT / "guide.css").write_text(guide_css + "\nhtml,body{background:#fbf1dc}\n")

fonts = re.search(r'href="(https://fonts.googleapis.com/css2[^"]+)"', B.FONTS).group(1)
ts = "// Generated by paratha/build_studio.py. Edit paratha/build.py and the templates, then rerun.\n"
ts += f"export const FONTS_HREF = {json.dumps(fonts)};\n"
ts += f"export const CONFIG = {json.dumps({'phone': B.PHONE, 'gst': 0.05, 'hooks': B.HOOKS, 'coupons': B.COUPONS})};\n"
ts += f"export const HOME_JSONLD = {json.dumps(B.jsonld_home(), ensure_ascii=False)};\n"
ts += f"export const CAT_JSONLD = {json.dumps(B.jsonld_catering(), ensure_ascii=False)};\n"
ts += f"export const GUIDE_JSONLD = {json.dumps(B.jsonld_guide(), ensure_ascii=False)};\n"
ts += f"export const GUIDE_BODY = {json.dumps(guide_body, ensure_ascii=False)};\n"
ts += f"export const HOME_BODY = {json.dumps(home_body, ensure_ascii=False)};\n"
ts += f"export const CAT_BODY = {json.dumps(cat_body, ensure_ascii=False)};\n"
(OUT / "content.gen.ts").write_text(ts)

# init modules: wrap the plain scripts so each page can start/stop them
def wrap(src, name, extra_imports=""):
    src = src.strip()
    if src.startswith("{") and src.endswith("}"): src = src[1:-1]
    # window-level listeners get the abort signal so they're removed when the page unmounts
    for a, b in [
        ("addEventListener('scroll', onScroll, { passive: true });", "addEventListener('scroll', onScroll, { passive: true, signal });"),
        ("addEventListener('keydown', e => { if (e.key === 'Escape') mnav && mnav.classList.remove('open'); });", "addEventListener('keydown', e => { if (e.key === 'Escape') mnav && mnav.classList.remove('open'); }, { signal });"),
        ("addEventListener('keydown', e => { if (e.key === 'Escape') close(); });", "addEventListener('keydown', e => { if (e.key === 'Escape') close(); }, { signal });"),
        ("addEventListener('scroll', readScroll, { passive: true });", "addEventListener('scroll', readScroll, { passive: true, signal });"),
        ("addEventListener('resize', resize);", "addEventListener('resize', resize, { signal });"),
        ("addEventListener('pointermove', e => { mx = e.clientX / innerWidth - .5; my = e.clientY / innerHeight - .5; }, { passive: true });", "addEventListener('pointermove', e => { mx = e.clientX / innerWidth - .5; my = e.clientY / innerHeight - .5; }, { passive: true, signal });"),
    ]:
        src = src.replace(a, b)
    return f"// @ts-nocheck\n// Generated by paratha/build_studio.py from paratha/{name}.js\n{extra_imports}export function init(signal: AbortSignal) {{\n{src}\n}}\n"

common = (HERE / "common.js").read_text().replace("const PL = window.PL;", "const PL = window.PL;", 1)
(OUT / "common.ts").write_text(wrap(common, "common"))
(OUT / "order.ts").write_text(wrap((HERE / "order.js").read_text(), "order"))

scene = (HERE / "scene.js").read_text()
imports = "".join(l + "\n" for l in scene.splitlines() if l.startswith("import "))
body = "\n".join(l for l in scene.splitlines() if not l.startswith("import "))
imports = imports.replace("'three/addons/", "'three/examples/jsm/")
body = body.replace("} catch (e) { document.body.classList.add('no-gl'); throw e; }", "} catch (e) { document.body.classList.add('no-gl'); return; }")
body = body.replace("function frame() {", "function frame() {\n  if (signal.aborted) { renderer.dispose(); return; }", 1)
(OUT / "scene.ts").write_text(wrap("{" + body + "}", "scene", imports))
print("ok")

